import { escapeHtml } from "@/lib/notify/templates";
import { csvCell, type Cell } from "./csv";
import { BANK_SECTIONS, SECTION_LABEL, sectionTable, summaryTable, type SectionTable } from "./sections";
import type { BankReport, PlatformSummary, ReportMeta } from "./types";

/**
 * Printable compliance report (pure): one self-contained HTML document with a print stylesheet — the user
 * prints it / saves it as PDF from the browser. No scripts, no external resources. Every value is escaped.
 */

/** Strict CSP for the standalone document (inline styles only). */
export const PRINT_CSP = "default-src 'none'; style-src 'unsafe-inline'; img-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'self'";

const CSS = `
  :root { color-scheme: light; }
  body { font: 12px/1.45 "Segoe UI", Arial, sans-serif; color: #111; margin: 24px; }
  h1 { font-size: 20px; margin: 0 0 4px; }
  h2 { font-size: 14px; margin: 22px 0 6px; border-bottom: 1px solid #999; padding-bottom: 2px; break-after: avoid; }
  .meta { display: grid; grid-template-columns: max-content 1fr; gap: 2px 14px; margin: 10px 0 4px; }
  .meta dt { color: #555; } .meta dd { margin: 0; }
  .hash { font-family: Consolas, monospace; font-size: 11px; word-break: break-all; }
  table { border-collapse: collapse; width: 100%; margin: 4px 0 8px; }
  th, td { border: 1px solid #bbb; padding: 3px 6px; text-align: left; vertical-align: top; }
  th { background: #eee; font-weight: 600; }
  td.num { text-align: right; font-variant-numeric: tabular-nums; }
  .note { color: #555; font-size: 11px; }
  .banner { background: #fff7d6; border: 1px solid #e5c55a; padding: 6px 10px; margin-bottom: 14px; }
  @page { size: A4 landscape; margin: 12mm; }
  @media print { body { margin: 0; } .banner { display: none; } tr { break-inside: avoid; } thead { display: table-header-group; } }
`;

function fmt(v: Cell): string {
  if (v instanceof Date) return v.toISOString().replace("T", " ").slice(0, 16) + " UTC";
  if (typeof v === "boolean") return v ? "yes" : "no";
  if (v === null || v === undefined) return "—";
  return Array.isArray(v) ? v.join(", ") : String(v);
}

function table(t: SectionTable, empty = "None in this period."): string {
  if (t.rows.length === 0) return `<p class="note">${escapeHtml(empty)}</p>`;
  const head = t.header.map((h) => `<th>${escapeHtml(h.replaceAll("_", " "))}</th>`).join("");
  const body = t.rows
    .map((r) => `<tr>${r.map((c) => `<td${typeof c === "number" ? ' class="num"' : ""}>${escapeHtml(fmt(c))}</td>`).join("")}</tr>`)
    .join("");
  return `<table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>`;
}

function header(meta: ReportMeta, sha256: string, title: string): string {
  const last = new Date(meta.to.getTime() - 1);
  const rows: [string, string][] = [
    ["Bank", meta.bankName],
    ["Period", `${meta.periodLabel} (${meta.from.toISOString().slice(0, 10)} – ${last.toISOString().slice(0, 10)}, UTC)`],
    ["Generated", fmt(meta.generatedAt)],
    ["Generated by", meta.generatedBy],
  ];
  return [
    `<div class="banner">To keep a PDF copy use your browser's Print → “Save as PDF”. The SHA-256 below is recorded in the audit chain.</div>`,
    `<h1>${escapeHtml(title)}</h1>`,
    `<dl class="meta">${rows.map(([k, v]) => `<dt>${escapeHtml(k)}</dt><dd>${escapeHtml(v)}</dd>`).join("")}<dt>Content SHA-256</dt><dd class="hash">${escapeHtml(sha256)}</dd></dl>`,
  ].join("");
}

function doc(title: string, body: string): string {
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${escapeHtml(title)}</title><style>${CSS}</style></head><body>${body}</body></html>`;
}

export function renderBankReportHtml(r: BankReport, sha256: string): string {
  const title = `Patch compliance report — ${r.meta.bankName}`;
  const parts = [header(r.meta, sha256, title)];
  parts.push(
    `<p class="note">Compliance is a snapshot at generation time. Compliant = scanned and no missing (NEEDED / FAILED) critical or important patch that is not superseded. Gap age = days since the vendor released the patch. Emergency = change request flagged emergency (two approvals).</p>`,
  );
  for (const s of BANK_SECTIONS) {
    if (s === "noncompliant") continue;
    parts.push(`<h2>${escapeHtml(SECTION_LABEL[s])}</h2>`, table(sectionTable(r, s)));
  }
  parts.push(`<p class="note">Per-endpoint detail: CSV export “Non-compliant endpoints”.</p>`);
  return doc(title, parts.join(""));
}

export function renderPlatformSummaryHtml(s: PlatformSummary, sha256: string): string {
  const title = "Patch compliance summary — all banks";
  return doc(title, [header(s.meta, sha256, title), `<h2>Banks</h2>`, table(summaryTable(s), "No banks.")].join(""));
}

/** Plain CSV text of a table (small sections; the big endpoint list is streamed). */
export function tableCsv(t: SectionTable): string {
  return [t.header.map((h) => csvCell(h)).join(","), ...t.rows.map((r) => r.map(csvCell).join(","))].join("\r\n") + "\r\n";
}
