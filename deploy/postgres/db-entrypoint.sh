#!/bin/bash
# PostgreSQL primary wrapper (runs as root, before the official entrypoint drops to "postgres").
#
# 1. Secrets on the host are 0600 and owned by the app uid (10001). The official entrypoint reads
#    POSTGRES_PASSWORD_FILE as root, but init scripts run as "postgres" — so copy the role passwords
#    they need into a root-only tmpfs, readable by postgres only.
# 2. TLS: the server key/certificate (secrets pg_tls_key / pg_tls_cert, generate-secrets.sh) are copied
#    the same way (PostgreSQL insists on a key owned by its user, 0600/0400) and ssl=on is added.
# 3. Access control (pg_hba) is generated on EVERY start into the tmpfs and passed as hba_file, so it is
#    managed here and not by whatever is in PGDATA:
#      - superuser "postgres" over the network ONLY from DB_ADMIN_SUBNET (the backup container's
#        "db-admin" network); web/fetcher/migrate on the "data" network can never log in as postgres;
#      - replication only as "replicator"; app/owner roles only to the PatchGate database;
#      - every network connection must use TLS (hostssl) when the certificate is present;
#      - local socket: peer (restore.sh / healthcheck run `-u postgres` inside this container).
set -euo pipefail

dest=/run/pg-secrets
install -d -m 0700 -o postgres -g postgres "$dest"
for name in db_owner_password db_app_password replication_password pg_tls_key pg_tls_cert; do
  if [ -r "/run/secrets/$name" ]; then
    install -m 0400 -o postgres -g postgres "/run/secrets/$name" "$dest/$name"
  fi
done

db="${POSTGRES_DB:-patchgate}"
owner="${PATCHGATE_DB_OWNER:-patchgate_owner}"
app="${PATCHGATE_DB_APP:-patchgate_app}"
admin_subnet="${DB_ADMIN_SUBNET:-172.30.30.0/24}"
[[ "$admin_subnet" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$ ]] || { echo "db-entrypoint: invalid DB_ADMIN_SUBNET" >&2; exit 1; }

extra=()
host=host
if [ -s "$dest/pg_tls_key" ] && [ -s "$dest/pg_tls_cert" ]; then
  host=hostssl
  extra+=(-c ssl=on -c "ssl_cert_file=$dest/pg_tls_cert" -c "ssl_key_file=$dest/pg_tls_key" -c ssl_min_protocol_version=TLSv1.2)
else
  echo '{"level":"warn","msg":"db.tls_disabled","component":"db","reason":"pg_tls_key/pg_tls_cert secrets missing (run scripts/generate-secrets.sh)"}' >&2
fi

hba="$dest/pg_hba.conf"
cat > "$hba" <<HBA
# Generated by db-entrypoint.sh at container start — edit deploy/postgres/db-entrypoint.sh, not this file.
# TYPE  DATABASE     USER                ADDRESS            METHOD
local   all          all                                    peer
$host replication  replicator          samenet            scram-sha-256
$host all          postgres            $admin_subnet      scram-sha-256
host    all          postgres            all                reject
host    all          replicator          all                reject
$host $db          $owner,$app         samenet            scram-sha-256
host    all          all                 all                reject
HBA
chown postgres:postgres "$hba"
chmod 0400 "$hba"
extra+=(-c "hba_file=$hba")

# Only add server options when the command is the postgres server itself.
if [ "${1:-}" = "postgres" ]; then
  set -- "$@" "${extra[@]}"
fi
exec docker-entrypoint.sh "$@"
